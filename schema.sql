        ON DELETE CASCADE,

    CONSTRAINT FK_FALAIDIOM_PESSOAL
        FOREIGN KEY (fk_PESSOAL)
        REFERENCES PESSOAL(fk_CONTA)
        ON DELETE CASCADE
