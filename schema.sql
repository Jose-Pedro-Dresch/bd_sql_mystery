CREATE TABLE IF NOT EXISTS APLICAAVAGA (
    DtAplccao TIMESTAMP NOT NULL,
    SttusAplccao VARCHAR(50),
    fk_VAGAEMPREGO INT NOT NULL,
    fk_PESSOAL INT NOT NULL,

    PRIMARY KEY (fk_VAGAEMPREGO, fk_PESSOAL),

    CONSTRAINT FK_APLICA_VAGA
        FOREIGN KEY (fk_VAGAEMPREGO)
        REFERENCES VAGAEMPREGO(IDVagaEmp)
        ON DELETE CASCADE,

    CONSTRAINT FK_APLICA_PESSOAL
        FOREIGN KEY (fk_PESSOAL)
        REFERENCES PESSOAL(fk_CONTA)
        ON DELETE CASCADE
);

CREATE TABLE  IF NOT EXISTS CONEXAO (
    DtEnvConv TIMESTAMP NOT NULL,
    DtAceitConv TIMESTAMP,
    StatusConexao VARCHAR(50),
    fk_PESSOAL_1 INT NOT NULL,
    fk_PESSOAL_2 INT NOT NULL,

    PRIMARY KEY (fk_PESSOAL_1, fk_PESSOAL_2),

    CONSTRAINT FK_CONEXAO_PESSOAL1
        FOREIGN KEY (fk_PESSOAL_1)
        REFERENCES PESSOAL(fk_CONTA)
        ON DELETE CASCADE,

    CONSTRAINT FK_CONEXAO_PESSOAL2
        FOREIGN KEY (fk_PESSOAL_2)
        REFERENCES PESSOAL(fk_CONTA)
        ON DELETE CASCADE,

    CONSTRAINT CHK_CONEXAO_DIFERENTE
        CHECK (fk_PESSOAL_1 <> fk_PESSOAL_2)
);