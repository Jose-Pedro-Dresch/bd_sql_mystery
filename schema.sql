CREATE TABLE IF NOT EXISTS FALAIDIOM (
    NvlProfic VARCHAR(50),
    fk_IDIOMA INT NOT NULL,
    fk_PESSOAL INT NOT NULL,

    PRIMARY KEY (fk_IDIOMA, fk_PESSOAL),

    CONSTRAINT FK_FALAIDIOM_IDIOMA
